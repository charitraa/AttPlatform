export function DemoBadge({ className }: { className?: string }) {
  return (
    <Badge variant="outline" className={cn('border-warning/50 text-warning', className)} title="Generated by the offline demo provider, not a real model">
      Demo AI
    </Badge>
  )
}

/** Confidence as text plus a thin meter; the number is always visible, so the bar is never the only signal. */
export function Confidence({ value }: { value: number | null }) {
  if (value === null) return null
  const pct = Math.round(value * 100)
  return (
    <span className="inline-flex items-center gap-1.5 text-xs text-muted-foreground" title="Model-reported confidence">
      <span className="h-1.5 w-12 rounded-full bg-muted" aria-hidden><span className="block h-1.5 rounded-full bg-series-1" style={{ width: `${pct}%` }} /></span>
      {pct}% confident
    </span>
  )
}

function OverrideDialog({ rec, ticketId, onClose }: { rec: Recommendation; ticketId: string; onClose: () => void }) {
  const decide = useDecide(ticketId)
  const categories = useCategories()
  const members = useMembers({ is_active: 'true', page_size: 100 })
  const [value, setValue] = useState('')
  const [note, setNote] = useState('')
  const [error, setError] = useState<string | null>(null)
  const people = (members.data?.results ?? []).filter((m) =>
    rec.type === 'technician' ? m.role.code === 'field_technician' : ['support_agent', 'ops_manager', 'org_admin', 'super_admin'].includes(m.role.code))

  const payload = (): Record<string, unknown> => {
    if (rec.type === 'priority') return { priority: value }
    if (rec.type === 'category') return { category_id: value }
    return { user_id: value }
  }

  const submit = async () => {
    setError(null)
    try {
      await decide.mutateAsync({ id: rec.id, decision: 'override', value: payload(), note })
      toast.success(`${TYPE_LABEL[rec.type]} set manually`)
      onClose()
    } catch (e) {
      setError(firstErrorMessage(e))
    }
  }

  return (
    <Dialog open onOpenChange={(o) => { if (!o) onClose() }}>
      <DialogContent>
        <DialogHeader>
          <DialogTitle>Choose a different {TYPE_LABEL[rec.type].toLowerCase()}</DialogTitle>
          <DialogDescription>AI suggested {recommendationValue(rec)}. Your choice is applied and recorded as an override.</DialogDescription>
        </DialogHeader>
        <div className="grid gap-4">
          {error && <p role="alert" className="text-sm text-destructive">{error}</p>}
          <Field label={TYPE_LABEL[rec.type]}>
            <NativeSelect value={value} onChange={(e) => setValue(e.target.value)}>
              <option value="">Choose…</option>
              {rec.type === 'priority' && PRIORITIES.map((p) => <option key={p} value={p}>{PRIORITY_LABEL[p]}</option>)}
              {rec.type === 'category' && categories.data?.map((c) => <option key={c.id} value={c.id}>{c.full_name}</option>)}
              {(rec.type === 'assignee' || rec.type === 'technician') && people.map((m) => <option key={m.id} value={m.id}>{m.user.full_name}</option>)}
            </NativeSelect>
          </Field>
          <Field label="Why? (optional)" description="Helps measure and improve AI accuracy.">
            <Input value={note} onChange={(e) => setNote(e.target.value)} maxLength={500} />
          </Field>
        </div>
        <DialogFooter>
          <Button variant="outline" onClick={onClose}>Cancel</Button>
          <Button onClick={submit} disabled={!value || decide.isPending}>Apply</Button>
        </DialogFooter>
      </DialogContent>
    </Dialog>
  )
}

function RecommendationCard({ rec, ticketId, canDecide }: { rec: Recommendation; ticketId: string; canDecide: boolean }) {
  const decide = useDecide(ticketId)
  const [overriding, setOverriding] = useState(false)
  const act = async (decision: 'accept' | 'reject') => {
    try {
      await decide.mutateAsync({ id: rec.id, decision })
      toast.success(decision === 'accept' ? `${TYPE_LABEL[rec.type]} updated to ${recommendationValue(rec)}` : 'Suggestion dismissed')
    } catch (e) {
      toast.error(firstErrorMessage(e))
    }
  }
  return (
    <li className="space-y-2 rounded-lg border p-3">
      <div className="flex flex-wrap items-baseline justify-between gap-x-2 gap-y-1">
        <span className="text-sm">
          <span className="text-muted-foreground">{TYPE_LABEL[rec.type]}: </span>
          <span className="font-medium">{recommendationValue(rec)}</span>
          {rec.previous_value && <span className="text-xs text-muted-foreground"> (now {recommendationValue(rec, rec.previous_value)})</span>}
        </span>
        <Confidence value={rec.confidence} />
      </div>
      {rec.reasoning && <p className="text-xs text-muted-foreground">{rec.reasoning}</p>}
      {canDecide && (
        <div className="flex flex-wrap gap-1.5">
          <Button size="xs" onClick={() => act('accept')} disabled={decide.isPending}><Check /> Accept</Button>
          <Button size="xs" variant="outline" onClick={() => setOverriding(true)}>Choose other</Button>
          <Button size="xs" variant="ghost" onClick={() => act('reject')} disabled={decide.isPending} aria-label={`Dismiss ${TYPE_LABEL[rec.type]} suggestion`}><X /> Dismiss</Button>
        </div>
      )}
      {overriding && <OverrideDialog rec={rec} ticketId={ticketId} onClose={() => setOverriding(false)} />}
    </li>
  )
}

function SummaryBlock({ a }: { a: Analysis }) {
  const out = a.output as { summary: string; key_points: string[]; troubleshooting_done: string[]; open_questions: string[] }
  const list = (title: string, items: string[]) => items.length > 0 && (
    <div><p className="text-xs font-medium text-muted-foreground">{title}</p><ul className="ml-4 list-disc text-sm">{items.map((i) => <li key={i}>{i}</li>)}</ul></div>
  )
  return (
    <div className="space-y-2 rounded-lg bg-muted/50 p-3">
      <p className="text-sm">{out.summary}</p>
      {list('Key points', out.key_points)}
      {list('Already tried', out.troubleshooting_done)}
      {list('Open questions', out.open_questions)}
    </div>
  )
}

function RoutingDetails({ a }: { a: Analysis }) {
  const [open, setOpen] = useState(false)
  const agents = (a.output?.agents ?? []) as { user_id: string; name: string; score: number; explanation: string }[]
  if (!agents.length) return <p className="text-xs text-muted-foreground">No eligible agents to rank.</p>
  return (
    <div>
      <button type="button" className="inline-flex items-center gap-1 text-xs text-muted-foreground hover:text-foreground" onClick={() => setOpen((v) => !v)} aria-expanded={open}>
        <ChevronDown className={cn('size-3.5 transition-transform', open && 'rotate-180')} /> Why these candidates?
      </button>
      {open && (
        <ol className="mt-2 space-y-1.5">
          {agents.map((c, i) => (
            <li key={c.user_id} className="text-xs">
              <span className="font-medium">{i + 1}. {c.name}</span> <span className="text-muted-foreground">score {c.score.toFixed(2)}</span>
              <span className="block text-muted-foreground">{c.explanation}</span>
            </li>
          ))}
        </ol>
      )}
    </div>
  )
}

export function AIPanel({ ticketId, closed }: { ticketId: string; closed: boolean }) {
  const canUse = useCan('ai.use')
  const canDecide = useCan('ai.override')
  const ai = useTicketAI(ticketId, canUse)
  const run = useRunTicketAI(ticketId)
  if (!canUse) return null

  const analyses = ai.data?.analyses ?? []
  const byKind = Object.fromEntries(analyses.map((a) => [a.kind, a])) as Partial<Record<Analysis['kind'], Analysis>>
  const triage = ['classification', 'priority', 'routing'].map((k) => byKind[k as Analysis['kind']]).filter(Boolean) as Analysis[]
  const running = analyses.some((a) => a.status === 'pending' || a.status === 'running')
  const failed = triage.filter((a) => a.status === 'failed')
  const pending = (ai.data?.recommendations ?? []).filter((r) => r.status === 'pending')
  const decided = (ai.data?.recommendations ?? []).filter((r) => !['pending', 'superseded'].includes(r.status)).slice(0, 4)
  const mock = analyses.some((a) => a.is_mock)

  const start = async (kinds: Analysis['kind'][]) => {
    try {
      await run.mutateAsync(kinds)
    } catch (e) {
      toast.error(firstErrorMessage(e))
    }
  }

  return (
    <Card>
      <CardHeader className="flex flex-row items-center justify-between gap-2">
        <CardTitle className="flex items-center gap-2"><Sparkles className="size-4 text-primary" /> AI assistance</CardTitle>
        {mock && <DemoBadge />}
      </CardHeader>
      <CardContent className="space-y-4">
        {ai.isPending ? <p className="text-sm text-muted-foreground">Loading…</p> : (
          <>
            {ai.data && !ai.data.ai_enabled && <p className="text-xs text-muted-foreground">Automatic analysis is turned off for your organization. You can still run it here.</p>}
            {running && <p className="flex items-center gap-2 text-sm text-muted-foreground" role="status"><Loader2 className="size-4 animate-spin" /> Analysing…</p>}
            {failed.length > 0 && !running && (
              <div role="alert" className="flex items-start gap-2 rounded-lg border border-destructive/30 bg-destructive/5 p-2 text-xs">
                <AlertTriangle className="mt-0.5 size-3.5 shrink-0 text-destructive" />
                <span>AI analysis didn't complete ({failed[0].error || 'unknown error'}). The ticket works normally without it.</span>
              </div>
            )}
            {pending.length > 0 ? (
              <ul className="space-y-2">{pending.map((r) => <RecommendationCard key={r.id} rec={r} ticketId={ticketId} canDecide={canDecide && !closed} />)}</ul>
            ) : !running && triage.length > 0 && failed.length < triage.length && (
              <p className="text-sm text-muted-foreground">No open suggestions. The ticket matches what AI would choose, or suggestions were already decided.</p>
            )}
            {byKind.routing?.status === 'completed' && <RoutingDetails a={byKind.routing} />}
            {byKind.summary?.status === 'completed' && <SummaryBlock a={byKind.summary} />}
            {decided.length > 0 && (
              <ul className="space-y-1 border-t pt-3 text-xs text-muted-foreground">
                {decided.map((r) => (
                  <li key={r.id}>
                    {TYPE_LABEL[r.type]} {recommendationValue(r)}: {r.status === 'auto_applied' ? 'applied automatically' : r.status}
                    {r.decided_by && ` by ${r.decided_by}`}{r.decided_at && ` · ${formatRelative(r.decided_at)}`}
                  </li>
                ))}
              </ul>
            )}
            <div className="flex flex-wrap gap-2">
              <Button size="sm" variant="outline" onClick={() => start(['classification', 'priority', 'routing'])} disabled={running || run.isPending || closed}>
                <RotateCw /> {triage.length ? 'Re-run triage' : 'Analyse ticket'}
              </Button>
              <Button size="sm" variant="outline" onClick={() => start(['summary'])} disabled={running || run.isPending}>
                Summarise
              </Button>
            </div>
          </>
        )}
      </CardContent>
    </Card>
  )
}
